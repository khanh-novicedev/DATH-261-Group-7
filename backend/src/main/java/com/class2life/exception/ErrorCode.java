package com.class2life.exception;


import org.springframework.http.HttpStatus;
public enum ErrorCode {
    // 400
    VALIDATION_ERROR(HttpStatus.BAD_REQUEST), INVALID_RESET_TOKEN(HttpStatus.BAD_REQUEST), INVALID_FILE(HttpStatus.BAD_REQUEST),
    COURSE_NOT_PUBLISHED(HttpStatus.BAD_REQUEST), DEADLINE_PASSED(HttpStatus.BAD_REQUEST), ASSIGNMENT_TYPE_MISMATCH(HttpStatus.BAD_REQUEST),
    LESSON_NOT_LIVE_PRACTICE(HttpStatus.BAD_REQUEST),
    // 401
    UNAUTHORIZED(HttpStatus.UNAUTHORIZED), TOKEN_EXPIRED(HttpStatus.UNAUTHORIZED), INVALID_CREDENTIALS(HttpStatus.UNAUTHORIZED), INVALID_REFRESH_TOKEN(HttpStatus.UNAUTHORIZED),
    // 403
    FORBIDDEN(HttpStatus.FORBIDDEN), ACCOUNT_SUSPENDED(HttpStatus.FORBIDDEN), NOT_ENROLLED(HttpStatus.FORBIDDEN), NOT_IN_SESSION(HttpStatus.FORBIDDEN),
    // 404
    USER_NOT_FOUND(HttpStatus.NOT_FOUND), COURSE_NOT_FOUND(HttpStatus.NOT_FOUND), LESSON_NOT_FOUND(HttpStatus.NOT_FOUND),
    ENROLMENT_NOT_FOUND(HttpStatus.NOT_FOUND), ASSIGNMENT_NOT_FOUND(HttpStatus.NOT_FOUND), SUBMISSION_NOT_FOUND(HttpStatus.NOT_FOUND), QNA_NOT_FOUND(HttpStatus.NOT_FOUND), REPORT_NOT_FOUND(HttpStatus.NOT_FOUND), NOTIFICATION_NOT_FOUND(HttpStatus.NOT_FOUND), SESSION_NOT_FOUND(HttpStatus.NOT_FOUND),
    // 409
    EMAIL_ALREADY_EXISTS(HttpStatus.CONFLICT), LESSON_IN_USE(HttpStatus.CONFLICT), COURSE_HAS_ENROLMENTS(HttpStatus.CONFLICT), ALREADY_ENROLLED(HttpStatus.CONFLICT), REPORT_ALREADY_RESOLVED(HttpStatus.CONFLICT), INVALID_STATUS_TRANSITION(HttpStatus.CONFLICT), SESSION_NOT_COMPLETED(HttpStatus.CONFLICT),
    // 500
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR);
    private final HttpStatus status;
    ErrorCode(HttpStatus status) {
        this.status = status;
    }
    public HttpStatus getStatus() {
        return status;
    }
}

